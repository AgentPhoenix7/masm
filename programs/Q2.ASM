; Question 2
; Copy twenty bytes to DS:4000H and rearrange them so that
; a[0] < a[1] > a[2] < a[3] > ...

STACKSEG SEGMENT PARA STACK 'STACK'
    DW 128 DUP (?)
STACKSEG ENDS

DATASEG SEGMENT PARA PUBLIC 'DATA'
    Q2_TITLE DB 13,10,'QUESTION 2 - 20-BYTE ZIG-ZAG ARRAY',13,10,'$'
    Q2_RULE DB 'Required relation: a0 < a1 > a2 < a3 > ...',13,10,'$'
    Q2_INPUT_LABEL DB 'Input array:       $'
    Q2_BEFORE_LABEL DB 'Before, DS:4000H: $'
    Q2_AFTER_LABEL DB 'After,  DS:4000H: $'
    Q2_OK DB 'Verification: PASS - alternating < and > relations hold.',13,10,'$'
    Q2_FAIL DB 'Verification: FAIL',13,10,'$'
    VALID DB 1
INPUT_ARRAY DB 12H,05H,19H,02H,11H,08H,1FH,04H,16H,0AH
            DB 1BH,01H,0DH,07H,1DH,03H,14H,09H,18H,06H

    ORG 4000H
ZIGZAG_ARRAY DB 20 DUP (00H)
DATASEG ENDS

CODESEG SEGMENT PARA PUBLIC 'CODE'
    ASSUME CS:CODESEG, DS:DATASEG, ES:DATASEG, SS:STACKSEG

START:
    MOV AX, DATASEG
    MOV DS, AX
    MOV ES, AX

    LEA DX, Q2_TITLE
    CALL PRINT_DOS
    LEA DX, Q2_RULE
    CALL PRINT_DOS

    LEA DX, Q2_INPUT_LABEL
    CALL PRINT_DOS
    LEA SI, INPUT_ARRAY
    MOV CX, 20
    CALL PRINT_HEX_ARRAY
    CALL PRINT_CRLF

    LEA SI, INPUT_ARRAY
    MOV DI, 4000H
    MOV CX, 20
    CLD
    REP MOVSB

    LEA DX, Q2_BEFORE_LABEL
    CALL PRINT_DOS
    MOV SI, 4000H
    MOV CX, 20
    CALL PRINT_HEX_ARRAY
    CALL PRINT_CRLF

    MOV SI, 4000H
    MOV CX, 19
    XOR BL, BL
Q2_ZIGZAG:
    MOV AL, [SI]
    MOV AH, [SI+1]
    TEST BL, 1
    JNZ Q2_WANT_GREATER
    CMP AL, AH
    JB Q2_PAIR_OK
    JMP SHORT Q2_SWAP
Q2_WANT_GREATER:
    CMP AL, AH
    JA Q2_PAIR_OK
Q2_SWAP:
    MOV [SI], AH
    MOV [SI+1], AL
Q2_PAIR_OK:
    INC SI
    INC BL
    LOOP Q2_ZIGZAG

    LEA DX, Q2_AFTER_LABEL
    CALL PRINT_DOS
    MOV SI, 4000H
    MOV CX, 20
    CALL PRINT_HEX_ARRAY
    CALL PRINT_CRLF

    MOV VALID, 1
    MOV SI, 4000H
    MOV CX, 19
    XOR BL, BL
Q2_VERIFY:
    MOV AL, [SI]
    CMP BL, 0
    JNE Q2_VERIFY_GREATER
    CMP AL, [SI+1]
    JAE Q2_INVALID
    JMP SHORT Q2_VERIFY_NEXT
Q2_VERIFY_GREATER:
    CMP AL, [SI+1]
    JBE Q2_INVALID
Q2_VERIFY_NEXT:
    XOR BL, 1
    INC SI
    LOOP Q2_VERIFY
    JMP SHORT Q2_REPORT
Q2_INVALID:
    MOV VALID, 0
Q2_REPORT:
    CMP VALID, 1
    JNE Q2_REPORT_FAIL
    LEA DX, Q2_OK
    CALL PRINT_DOS
    JMP SHORT Q2_EXIT
Q2_REPORT_FAIL:
    LEA DX, Q2_FAIL
    CALL PRINT_DOS
Q2_EXIT:
    MOV AX, 4C00H
    INT 21H

    INCLUDE COMMON.INC
CODESEG ENDS
END START


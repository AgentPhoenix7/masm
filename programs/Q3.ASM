; Question 3
; Convert the 16-bit hexadecimal number 3FA7H into four ASCII characters.

STACKSEG SEGMENT PARA STACK 'STACK'
    DW 128 DUP (?)
STACKSEG ENDS

DATASEG SEGMENT PARA PUBLIC 'DATA'
    Q3_TITLE DB 13,10,'QUESTION 3 - HEXADECIMAL TO ASCII',13,10,'$'
    Q3_VALUE_LABEL DB 'Numeric input word: 0x$'
    Q3_BEFORE_LABEL DB 'ASCII buffer before conversion: $'
    Q3_TEXT_LABEL DB 'ASCII characters after conversion: $'
    Q3_BYTES_LABEL DB 'ASCII byte values after conversion: $'
HEX_VALUE DW 3FA7H
ASCII_RESULT DB 00H,00H,00H,00H,'$'
DATASEG ENDS

CODESEG SEGMENT PARA PUBLIC 'CODE'
    ASSUME CS:CODESEG, DS:DATASEG, SS:STACKSEG

START:
    MOV AX, DATASEG
    MOV DS, AX

    LEA DX, Q3_TITLE
    CALL PRINT_DOS
    LEA DX, Q3_VALUE_LABEL
    CALL PRINT_DOS
    MOV AX, HEX_VALUE
    CALL PRINT_HEX_WORD
    CALL PRINT_CRLF

    LEA DX, Q3_BEFORE_LABEL
    CALL PRINT_DOS
    LEA SI, ASCII_RESULT
    MOV CX, 4
    CALL PRINT_HEX_ARRAY
    CALL PRINT_CRLF

    MOV BX, HEX_VALUE
    LEA DI, ASCII_RESULT
    MOV CX, 4
Q3_CONVERT:
    ROL BX, 1
    ROL BX, 1
    ROL BX, 1
    ROL BX, 1
    MOV AL, BL
    AND AL, 0FH
    CMP AL, 09H
    JBE Q3_DECIMAL_DIGIT
    ADD AL, 07H
Q3_DECIMAL_DIGIT:
    ADD AL, '0'
    MOV [DI], AL
    INC DI
    LOOP Q3_CONVERT

    LEA DX, Q3_TEXT_LABEL
    CALL PRINT_DOS
    LEA DX, ASCII_RESULT
    CALL PRINT_DOS
    CALL PRINT_CRLF

    LEA DX, Q3_BYTES_LABEL
    CALL PRINT_DOS
    LEA SI, ASCII_RESULT
    MOV CX, 4
    CALL PRINT_HEX_ARRAY
    CALL PRINT_CRLF

    MOV AX, 4C00H
    INT 21H

    INCLUDE COMMON.INC
CODESEG ENDS
END START


; Question 4
; Interactive unsigned 8-bit calculator supporting +, -, * and /.

STACKSEG SEGMENT PARA STACK 'STACK'
    DW 128 DUP (?)
STACKSEG ENDS

DATASEG SEGMENT PARA PUBLIC 'DATA'
    Q4_TITLE DB 13,10,'QUESTION 4 - BASIC CALCULATOR',13,10,'$'
    Q4_RANGE DB 'Enter unsigned decimal operands from 0 through 255.',13,10,'$'
    PROMPT_FIRST DB 'First operand: $'
    PROMPT_OPERATOR DB 'Operator (+, -, *, /): $'
    PROMPT_SECOND DB 'Second operand: $'
    RESULT_LABEL DB 'Result: $'
    QUOTIENT_LABEL DB 'Quotient: $'
    REMAINDER_LABEL DB '  Remainder: $'
    INVALID_INPUT DB 'ERROR: input must be a decimal number from 0 through 255.',13,10,'$'
    INVALID_OPERATOR DB 'ERROR: unsupported operator.',13,10,'$'
    DIVIDE_ZERO DB 'ERROR: division by zero.',13,10,'$'
OPERAND1 DW 0
OPERAND2 DW 0
OPERATOR DB 0
QUOTIENT DW 0
REMAINDER DW 0
DATASEG ENDS

CODESEG SEGMENT PARA PUBLIC 'CODE'
    ASSUME CS:CODESEG, DS:DATASEG, SS:STACKSEG

START:
    MOV AX, DATASEG
    MOV DS, AX

    LEA DX, Q4_TITLE
    CALL PRINT_DOS
    LEA DX, Q4_RANGE
    CALL PRINT_DOS

    LEA DX, PROMPT_FIRST
    CALL PRINT_DOS
    CALL READ_UINT8
    JNC Q4_FIRST_OK
    JMP Q4_BAD_INPUT
Q4_FIRST_OK:
    MOV OPERAND1, AX
    CALL PRINT_CRLF

    LEA DX, PROMPT_OPERATOR
    CALL PRINT_DOS
    MOV AH, 01H
    INT 21H
    MOV OPERATOR, AL
    CALL DISCARD_LINE
    CALL PRINT_CRLF

    LEA DX, PROMPT_SECOND
    CALL PRINT_DOS
    CALL READ_UINT8
    JNC Q4_SECOND_OK
    JMP Q4_BAD_INPUT
Q4_SECOND_OK:
    MOV OPERAND2, AX
    CALL PRINT_CRLF

    MOV AL, OPERATOR
    CMP AL, '+'
    JE Q4_ADD
    CMP AL, '-'
    JE Q4_SUBTRACT
    CMP AL, '*'
    JE Q4_MULTIPLY
    CMP AL, '/'
    JE Q4_DIVIDE
    LEA DX, INVALID_OPERATOR
    CALL PRINT_DOS
    JMP Q4_EXIT_ERROR

Q4_ADD:
    MOV AX, OPERAND1
    ADD AX, OPERAND2
    LEA DX, RESULT_LABEL
    CALL PRINT_DOS
    CALL PRINT_UINT
    CALL PRINT_CRLF
    JMP Q4_EXIT_OK

Q4_SUBTRACT:
    LEA DX, RESULT_LABEL
    CALL PRINT_DOS
    MOV AX, OPERAND1
    CMP AX, OPERAND2
    JAE Q4_SUB_POSITIVE
    MOV DL, '-'
    CALL PRINT_CHAR
    MOV AX, OPERAND2
    SUB AX, OPERAND1
    JMP SHORT Q4_SUB_PRINT
Q4_SUB_POSITIVE:
    SUB AX, OPERAND2
Q4_SUB_PRINT:
    CALL PRINT_UINT
    CALL PRINT_CRLF
    JMP SHORT Q4_EXIT_OK

Q4_MULTIPLY:
    MOV AX, OPERAND1
    MOV BX, OPERAND2
    MUL BX
    LEA DX, RESULT_LABEL
    CALL PRINT_DOS
    CALL PRINT_UINT
    CALL PRINT_CRLF
    JMP SHORT Q4_EXIT_OK

Q4_DIVIDE:
    CMP OPERAND2, 0
    JE Q4_DIVIDE_ZERO
    MOV AX, OPERAND1
    XOR DX, DX
    DIV OPERAND2
    MOV QUOTIENT, AX
    MOV REMAINDER, DX
    LEA DX, QUOTIENT_LABEL
    CALL PRINT_DOS
    MOV AX, QUOTIENT
    CALL PRINT_UINT
    LEA DX, REMAINDER_LABEL
    CALL PRINT_DOS
    MOV AX, REMAINDER
    CALL PRINT_UINT
    CALL PRINT_CRLF
    JMP SHORT Q4_EXIT_OK

Q4_BAD_INPUT:
    CALL PRINT_CRLF
    LEA DX, INVALID_INPUT
    CALL PRINT_DOS
    JMP SHORT Q4_EXIT_ERROR
Q4_DIVIDE_ZERO:
    LEA DX, DIVIDE_ZERO
    CALL PRINT_DOS
Q4_EXIT_ERROR:
    MOV AX, 4C01H
    INT 21H
Q4_EXIT_OK:
    MOV AX, 4C00H
    INT 21H

; Reads a line containing an unsigned decimal number in the range 0..255.
; Returns AX = value and CF clear, or CF set for invalid input.
READ_UINT8 PROC NEAR
    PUSH BX
    PUSH CX
    PUSH DX
    PUSH SI
    XOR BX, BX
    XOR SI, SI
RU_READ:
    MOV AH, 01H
    INT 21H
    CMP AL, 13
    JE RU_FINISH
    CMP AL, 10
    JE RU_FINISH
    CMP AL, '0'
    JB RU_BAD
    CMP AL, '9'
    JA RU_BAD
    MOV DL, AL
    SUB DL, '0'
    XOR DH, DH
    MOV AX, BX
    SHL AX, 1
    MOV CX, AX
    SHL AX, 1
    SHL AX, 1
    ADD AX, CX
    ADD AX, DX
    CMP AX, 255
    JA RU_BAD
    MOV BX, AX
    INC SI
    JMP SHORT RU_READ
RU_FINISH:
    OR SI, SI
    JZ RU_INVALID
    MOV AX, BX
    CLC
    JMP SHORT RU_RETURN
RU_BAD:
    CMP AL, 13
    JE RU_INVALID
    CMP AL, 10
    JE RU_INVALID
RU_CONSUME:
    MOV AH, 01H
    INT 21H
    CMP AL, 13
    JE RU_INVALID
    CMP AL, 10
    JNE RU_CONSUME
RU_INVALID:
    STC
RU_RETURN:
    POP SI
    POP DX
    POP CX
    POP BX
    RET
READ_UINT8 ENDP

DISCARD_LINE PROC NEAR
    PUSH AX
DL_NEXT:
    MOV AH, 01H
    INT 21H
    CMP AL, 13
    JE DL_DONE
    CMP AL, 10
    JNE DL_NEXT
DL_DONE:
    POP AX
    RET
DISCARD_LINE ENDP

    INCLUDE COMMON.INC
CODESEG ENDS
END START

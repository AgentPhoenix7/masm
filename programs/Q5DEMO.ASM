; Question 5 demonstration program for STRLIB.LIB.

STACKSEG SEGMENT PARA STACK 'STACK'
    DW 128 DUP (?)
STACKSEG ENDS

DATASEG SEGMENT PARA PUBLIC 'DATA'
    Q5_TITLE DB 13,10,'QUESTION 5 - STRING OPERATION LIBRARY',13,10,'$'
    S1_LABEL DB 'String 1: $'
    S2_LABEL DB 'String 2: $'
    L1_LABEL DB 'STRLEN(string 1) = $'
    L2_LABEL DB 'STRLEN(string 2) = $'
    CMP_LABEL DB 'STRCMP result: $'
    CMP_LESS DB 'string 1 is less than string 2',13,10,'$'
    CMP_EQUAL DB 'strings are equal',13,10,'$'
    CMP_GREATER DB 'string 1 is greater than string 2',13,10,'$'
    REV_BEFORE DB 'Before STRREV: $'
    REV_AFTER DB 'After  STRREV: $'
STRING1 DB 'NETWORK',0
STRING2 DB 'NETWORL',0
LEN1 DW 0
LEN2 DW 0
DATASEG ENDS

CODESEG SEGMENT PARA PUBLIC 'CODE'
    ASSUME CS:CODESEG, DS:DATASEG, SS:STACKSEG
    EXTRN STRLEN:NEAR, STRCMP:NEAR, STRREV:NEAR

START:
    MOV AX, DATASEG
    MOV DS, AX

    LEA DX, Q5_TITLE
    CALL PRINT_DOS
    LEA DX, S1_LABEL
    CALL PRINT_DOS
    LEA SI, STRING1
    CALL PRINT_Z
    CALL PRINT_CRLF
    LEA DX, S2_LABEL
    CALL PRINT_DOS
    LEA SI, STRING2
    CALL PRINT_Z
    CALL PRINT_CRLF

    LEA SI, STRING1
    CALL STRLEN
    MOV LEN1, AX
    LEA DX, L1_LABEL
    CALL PRINT_DOS
    MOV AX, LEN1
    CALL PRINT_UINT
    CALL PRINT_CRLF

    LEA SI, STRING2
    CALL STRLEN
    MOV LEN2, AX
    LEA DX, L2_LABEL
    CALL PRINT_DOS
    MOV AX, LEN2
    CALL PRINT_UINT
    CALL PRINT_CRLF

    LEA SI, STRING1
    LEA DI, STRING2
    CALL STRCMP
    LEA DX, CMP_LABEL
    CALL PRINT_DOS
    CMP AX, 0
    JL Q5_LESS
    JG Q5_GREATER
    LEA DX, CMP_EQUAL
    JMP SHORT Q5_PRINT_COMPARE
Q5_LESS:
    LEA DX, CMP_LESS
    JMP SHORT Q5_PRINT_COMPARE
Q5_GREATER:
    LEA DX, CMP_GREATER
Q5_PRINT_COMPARE:
    CALL PRINT_DOS

    LEA DX, REV_BEFORE
    CALL PRINT_DOS
    LEA SI, STRING1
    CALL PRINT_Z
    CALL PRINT_CRLF

    LEA SI, STRING1
    CALL STRREV

    LEA DX, REV_AFTER
    CALL PRINT_DOS
    LEA SI, STRING1
    CALL PRINT_Z
    CALL PRINT_CRLF

    MOV AX, 4C00H
    INT 21H

PRINT_Z PROC NEAR
    PUSH AX
    PUSH DX
    PUSH SI
PZ_NEXT:
    MOV AL, [SI]
    OR AL, AL
    JZ PZ_DONE
    MOV DL, AL
    MOV AH, 02H
    INT 21H
    INC SI
    JMP SHORT PZ_NEXT
PZ_DONE:
    POP SI
    POP DX
    POP AX
    RET
PRINT_Z ENDP

    INCLUDE COMMON.INC
CODESEG ENDS
END START

